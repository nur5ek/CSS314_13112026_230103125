import argparse, json, multiprocessing as mp, time
from multiprocessing import shared_memory
from statistics import median
from harness import emit_verify_tag
SIZE=64_000_000

def copy_worker(an,bn,start,end):
    a=shared_memory.SharedMemory(name=an);b=shared_memory.SharedMemory(name=bn)
    try:
        dst=a.buf;src=b.buf;dst[start:end]=src[start:end]
        del dst,src
    finally:a.close();b.close()

def compute_worker(repetitions,queue):
    v=[1.0+i*0.0001 for i in range(16)]; a=0.99999999;b=0.00000001
    t=time.perf_counter_ns()
    for _ in range(repetitions):
        for j in range(16):v[j]=v[j]*a+b
    queue.put((time.perf_counter_ns()-t,sum(v)))

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--id',type=int,required=True);ap.add_argument('--physical',type=int,required=True);ap.add_argument('--quick',action='store_true');a=ap.parse_args()
    size=1_000_000 if a.quick else SIZE
    sm1=shared_memory.SharedMemory(create=True,size=size);sm2=shared_memory.SharedMemory(create=True,size=size)
    # Windows may lack available shared-memory capacity: test allocation on local machine.
    try:
        timings=[]
        for _ in range(2 if a.quick else 7):
            st=time.perf_counter_ns();ps=[mp.Process(target=copy_worker,args=(sm1.name,sm2.name,size*i//a.physical,size*(i+1)//a.physical)) for i in range(a.physical)]
            for p in ps:p.start()
            for p in ps:p.join()
            if any(p.exitcode for p in ps):raise RuntimeError('copy worker failed')
            timings.append((time.perf_counter_ns()-st)/1e9)
        t=median(timings);bw=2*size/t/1e9
    finally:sm1.close();sm2.close();sm1.unlink();sm2.unlink()
    # 16 scalar updates x 2 FLOPs per iteration. The task says 80M FMA FLOPs per worker.
    loops=1000 if a.quick else 1_875_000
    q=mp.Queue();st=time.perf_counter_ns();ps=[mp.Process(target=compute_worker,args=(loops,q)) for _ in range(a.physical)]
    for p in ps:p.start()
    results=[q.get() for _ in ps]
    for p in ps:p.join()
    elapsed=(time.perf_counter_ns()-st)/1e9
    gflops=a.physical*loops*16*2/elapsed/1e9
    out={'student_id':a.id,'quick':a.quick,'size_bytes_per_buffer':size,'copy_seconds':t,'bandwidth_gbs':bw,'compute_seconds':elapsed,'compute_gflops':gflops,'ridge_flops_per_byte':gflops/bw,'verify_note':'PHASE3 hash is generated by task3b_gemm.py'}
    open('phase3a.json','w').write(json.dumps(out,indent=2));print(json.dumps(out,indent=2))
if __name__=='__main__':mp.freeze_support();main()

